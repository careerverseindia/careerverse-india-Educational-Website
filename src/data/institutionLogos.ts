/**
 * Returns Primary Logo URL using Google Favicon V2 (128px high-resolution PNG, fast, zero rate limit)
 */
export function getInstitutionLogoUrl(slugOrId: string, name?: string): string {
  const domain = getInstitutionDomain(slugOrId, name);
  return `https://www.google.com/s2/favicons?domain=${domain}&sz=128`;
}

/**
 * Returns Secondary Logo URL using Google Favicon V2
 */
export function getInstitutionFaviconUrl(slugOrId: string, name?: string): string {
  const domain = getInstitutionDomain(slugOrId, name);
  return `https://www.google.com/s2/favicons?domain=${domain}&sz=128`;
}

/**
 * Returns Tertiary Logo URL using DuckDuckGo Icons API
 */
export function getInstitutionDdgLogoUrl(slugOrId: string, name?: string): string {
  const domain = getInstitutionDomain(slugOrId, name);
  return `https://icons.duckduckgo.com/ip3/${domain}.ico`;
}

/**
 * Generates a crisp, official academic brand SVG emblem as data URI.
 * Guaranteed to NEVER fail, NEVER stretch, and NEVER be blank!
 */
export function getInstitutionBrandSvg(name: string): string {
  const words = name.split(' ').filter(w => !['of', '&', 'and', 'the', 'in', 'online'].includes(w.toLowerCase()));
  const initials = words.slice(0, 2).map(w => w[0]).join('').toUpperCase() || 'CV';
  const cleanName = name.length > 22 ? name.substring(0, 20) + '…' : name;

  const svg = `
<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 240 120" width="240" height="120">
  <rect width="240" height="120" rx="12" fill="#FFFFFF"/>
  <rect x="4" y="4" width="232" height="112" rx="10" fill="#F8FAFC" stroke="#E2E8F0" stroke-width="1.5"/>
  <g transform="translate(18, 22)">
    <circle cx="38" cy="38" r="34" fill="#0B2A52" stroke="#C99A2E" stroke-width="2.5"/>
    <circle cx="38" cy="38" r="28" fill="none" stroke="#E5C66B" stroke-dasharray="3,2" stroke-width="1"/>
    <text x="38" y="45" font-family="system-ui, sans-serif" font-size="20" font-weight="900" fill="#FFFFFF" text-anchor="middle" letter-spacing="1">${initials}</text>
  </g>
  <g transform="translate(104, 38)">
    <text x="0" y="16" font-family="system-ui, sans-serif" font-size="13" font-weight="800" fill="#0B2A52">${cleanName}</text>
    <text x="0" y="34" font-family="system-ui, sans-serif" font-size="10" font-weight="700" fill="#C99A2E" letter-spacing="0.5">ACCREDITED PARTNER</text>
    <line x1="0" y1="42" x2="110" y2="42" stroke="#E2E8F0" stroke-width="1"/>
  </g>
</svg>`.trim();

  return `data:image/svg+xml;utf8,${encodeURIComponent(svg)}`;
}
